package de.aarondietz.beetmeister.data.firmware

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class BeetFirmwareImageParserTest {
    @Test
    fun parsesEmbeddedMetadataAndSha256() {
        val image = byteArrayOf(
            0x00, 0x00, 0x00, 0x00,
            0x42, 0x54, 0x4D, 0x54, 0x01, 0x00, 0x56, 0x00, 0x53, 0x3A, 0x08.toByte(), 0xF3.toByte(),
            0x01, 0x00, 0x0B, 0x00, 0x62, 0x65, 0x65, 0x74, 0x6D, 0x65, 0x69, 0x73, 0x74, 0x65, 0x72,
            0x02, 0x00, 0x05, 0x00, 0x72, 0x65, 0x76, 0x5F, 0x61,
            0x03, 0x00, 0x03, 0x00, 0x64, 0x65, 0x76,
            0x04, 0x00, 0x03, 0x00, 0x64, 0x65, 0x76,
            0x05, 0x00, 0x04, 0x00, 0x01, 0x00, 0x00, 0x00,
            0x06, 0x00, 0x04, 0x00, 0x09, 0x00, 0x00, 0x00,
            0x07, 0x00, 0x07, 0x00, 0x62, 0x75, 0x6E, 0x64, 0x6C, 0x65, 0x64,
            0x08, 0x00, 0x05, 0x00, 0x72, 0x65, 0x76, 0x5F, 0x61,
            0x01, 0x02, 0x03,
        )

        val parsed = BeetFirmwareImageParser.parseImage(image)

        assertEquals("beetmeister", parsed.metadata.productId)
        assertEquals("rev_a", parsed.metadata.hardwareRev)
        assertEquals("dev", parsed.metadata.firmwareVersion)
        assertEquals("dev", parsed.metadata.buildLabel)
        assertEquals(1, parsed.metadata.maintenanceProtocolVersion)
        assertEquals(9, parsed.metadata.runtimeProtocolVersion)
        assertEquals("bundled", parsed.metadata.imageKind)
        assertEquals(listOf("rev_a"), parsed.metadata.compatibleHardwareRevs)
        assertEquals(image.size, parsed.imageSize)
        assertTrue(parsed.sha256Hex.matches(Regex("[0-9a-f]{64}")))
    }
}
